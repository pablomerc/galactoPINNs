"""Build the appendix table of acceleration provenance + the bib entries behind it.

Writes  <paper>/sections/table_catalog_sources.tex   (deluxetable, one row per pulsar)
        ./catalog_sources.bib                         (entries built from the ATNF reference file;
                                                       no DOIs -- check against ADS before submission)
"""
import re
from pathlib import Path
import pandas as pd
from astropy.coordinates import SkyCoord
import astropy.units as u
from programs import TAGS, program, bibkey

HERE = Path(__file__).resolve().parent
PAPER = HERE.parents[3] / "accelerations-paper"
version = (HERE / "atnf_version.txt").read_text().strip()

# ---- bib entries from psrcat_ref -------------------------------------------------------------
JOURNAL = {"apj": r"\apj", "apjl": r"\apjl", "apjs": r"\apjs", "mnras": r"\mnras", "aap": r"\aap",
           "aj": r"\aj", "nature": "Nature", "science": "Science", "prd": r"\prd", "aapl": r"\aap"}
raw = open(HERE / "atnf_cache/psrcat_tar/psrcat_ref", encoding="latin-1").read()
blocks = {}
for blk in re.split(r"\n(?=\*\*\*)", raw):
    m = re.match(r"\*\*\*(\S+)\s+\S+:\s*(.*)", blk, re.S)
    if m: blocks[m.group(1)] = " ".join(m.group(2).split())

def authors_to_bibtex(s):
    toks = [t.strip() for t in s.replace(" & ", ", ").split(",") if t.strip()]
    names, i = [], 0
    while i < len(toks):
        if i + 1 < len(toks) and re.fullmatch(r"(?:[A-Z][a-z]?\.\s*-?)+", toks[i + 1]):
            names.append(f"{toks[i]}, {toks[i + 1]}"); i += 2
        elif re.fullmatch(r"et al\.?", toks[i]):
            names.append("others"); i += 1                # BibTeX convention for truncated lists
        else:
            names.append("{" + toks[i] + "}"); i += 1
    return " and ".join(names)

def bib_entry(tag):
    key = bibkey(tag); blk = blocks[tag]
    m = re.match(r"(.*?),\s*(\d{4})[a-z]?\.\s+(.*)", blk, re.S)
    authors, year, rest = m.groups()
    m2 = re.match(r"(.*)\.\s+(\S+),\s*(\d+)(?:\((\d+)\))?,\s*([A-Za-z]?\d+(?:-[A-Za-z]?\d+)?)\+?\.?\s*$", rest)
    if m2:
        title, journal, volume, issue, pages = m2.groups()
    else:                                                    # unrecognised tail: keep it all as the title
        title, journal, volume, issue, pages = rest.rstrip("."), "", "", "", ""
        print(f"  [check] {tag}: could not split journal/volume/pages from: {rest[-80:]}")
    jn = JOURNAL.get(journal.lower(), journal)
    fields = [f"  author = {{{authors_to_bibtex(authors)}}}", f"  title = {{{{{title}}}}}", f"  year = {{{year}}}"]
    if journal: fields += [f"  journal = {{{jn}}}", f"  volume = {{{volume}}}", f"  pages = {{{pages}}}"]
    fields.append(f"  note = {{ATNF psrcat reference tag {tag}; entry built from the catalogue reference file, no DOI}}")
    return f"@ARTICLE{{{key},\n" + ",\n".join(fields) + "\n}\n"

entries = [bib_entry(t) for t in TAGS]
entries.append("""@ARTICLE{manchester2005-atnf,
  author = {Manchester, R. N. and Hobbs, G. B. and Teoh, A. and Hobbs, M.},
  title = {{The Australia Telescope National Facility Pulsar Catalogue}},
  journal = {\\aj},
  year = {2005},
  volume = {129},
  pages = {1993-2006},
  doi = {10.1086/428488}
}
""")
(HERE / "catalog_sources.bib").write_text("\n".join(entries))

# ---- table ------------------------------------------------------------------------------------
df = pd.read_csv(HERE / "donlon52_refs.csv")
df["program"] = df.tag.map(program)
df["dec"] = SkyCoord(l=df.GL.to_numpy() * u.deg, b=df.GB.to_numpy() * u.deg, frame="galactic").icrs.dec.deg
df["_sort"] = df.psrj.where(df.psrj.astype(str).str.len() > 0, df.name)
df = df.sort_values("_sort").reset_index(drop=True)     # RA order via J-name

def num(x, plus=False):
    s = f"{x:+.1f}" if plus else f"{x:.1f}"
    return "$" + s.replace("-", "-") + "$" if s.startswith(("-", "+")) else s

lines = []
for _, r in df.iterrows():
    name = r["name"].replace("-", "$-$")
    ch = r"$\dot P_b$" if r.channel == "PB" else r"$\dot P$"
    ref = rf"\citet{{{bibkey(r.tag)}}}" if bibkey(r.tag) else r.tag
    lines.append(f"{name} & {r.GL:.1f} & {num(r.GB)} & {num(r.dec, plus=True)} & {ch} & {r.program} & {ref} \\\\")
counts = df.program.value_counts()
tex = rf"""%% Generated by clean_experiments/paper_figures/sky_coverage/make_appendix_table.py -- do not edit by hand.
\startlongtable
\begin{{deluxetable}}{{lrrrccl}}
\tablecaption{{Provenance of the acceleration measurement for each pulsar in the
\citet{{donlon2025-empiricalmodeling}} catalog, as recorded in the ATNF Pulsar Catalogue
\citep[version {version};][]{{manchester2005-atnf}}. \label{{tab:catalog_sources}}}}
\tablehead{{\colhead{{PSR}} & \colhead{{$\ell$}} & \colhead{{$b$}} & \colhead{{$\delta$}} &
            \colhead{{Channel}} & \colhead{{Program}} & \colhead{{Reference}} \\
            \colhead{{}} & \colhead{{(deg)}} & \colhead{{(deg)}} & \colhead{{(deg)}} & \colhead{{}} & \colhead{{}} & \colhead{{}}}}
\startdata
""" + "\n".join(lines) + rf"""
\enddata
\tablecomments{{Channel: $\dot P_b$, orbital period derivative (binary channel); $\dot P$, spin
period derivative. Program: the pulsar timing array whose data release the ATNF catalogue adopts
for that parameter ({counts.get('NANOGrav',0)} NANOGrav, {counts.get('EPTA',0)} EPTA,
{counts.get('PPTA',0)} PPTA); ``Other'' ({counts.get('Other',0)}) denotes a dedicated timing
study of the individual system. $\delta$ is the J2000 declination. J0737$-$3039B is omitted
(companion of J0737$-$3039A).}}
\end{{deluxetable}}
"""
(PAPER / "sections" / "table_catalog_sources.tex").write_text(tex)
print(f"wrote table ({len(df)} rows) and {len(entries)} bib entries; programs: {dict(counts)}")
